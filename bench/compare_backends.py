"""
Cross-backend agreement check on the deterministic synthetic chain.

Solves the same chain with the python (reference), numpy, and cpp backends
and reports the maximum absolute IV difference between them, plus how many
contracts each path (Newton vs Brent fallback) handled in C++.

Usage:
    python bench/compare_backends.py              # 100k contracts
    python bench/compare_backends.py --n 10000

Writes bench/agreement.md.
"""

import argparse
import platform
import sys
import time
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from vol_surface_engine import iv_solver  # noqa: E402
from vol_surface_engine.synthetic_chain import generate_chain  # noqa: E402

RATE = 0.03


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--n", type=int, default=100_000)
    ap.add_argument("--out", default=str(Path(__file__).with_name("agreement.md")))
    args = ap.parse_args()

    if not iv_solver.CPP_AVAILABLE:
        sys.exit("C++ extension not built; see README for build steps")

    df = generate_chain(args.n, rate=RATE)
    price = df["mid"].to_numpy()
    S = df["underlying_price"].to_numpy()
    K = df["strike"].to_numpy()
    T = df["time_to_expiry"].to_numpy()
    call = (df["option_type"] == "C").to_numpy()
    truth = df["true_iv"].to_numpy()

    iv, secs = {}, {}
    for backend in ("cpp", "numpy", "python"):
        t0 = time.perf_counter()
        iv[backend] = iv_solver.implied_vol_array(price, S, K, T, RATE, call, backend=backend)
        secs[backend] = time.perf_counter() - t0
        print(f"{backend:>6}: {secs[backend]:.2f}s", flush=True)

    status = np.empty(args.n, dtype=np.int8)
    out = np.empty(args.n)
    iv_solver._iv_core.implied_vol_batch_status(S, K, T, price, call.view(np.uint8), RATE,
                                                 out, status)
    assert np.array_equal(out, iv["cpp"], equal_nan=True)

    def nan_mismatch(a, b):
        return int(np.sum(np.isnan(a) != np.isnan(b)))

    def max_diff(a, b):
        both = ~np.isnan(a) & ~np.isnan(b)
        d = np.abs(a[both] - b[both])
        return float(d.max()), int(np.argmax(d)) if d.size else -1, both

    lines = [
        f"# Backend agreement on the {args.n:,}-contract synthetic chain",
        "",
        "Generated by `python bench/compare_backends.py --n {}`.".format(args.n),
        f"Python {platform.python_version()}, NumPy {np.__version__}, "
        f"machine `{platform.machine()}`.",
        "",
        "| Comparison | max abs IV diff | rows where only one side is NaN |",
        "|---|---|---|",
    ]
    for a, b in [("cpp", "python"), ("numpy", "python"), ("cpp", "numpy")]:
        m, _, _ = max_diff(iv[a], iv[b])
        lines.append(f"| {a} vs {b} | {m:.3e} | {nan_mismatch(iv[a], iv[b])} |")
    for b in ("python", "numpy", "cpp"):
        m, _, _ = max_diff(iv[b], truth)
        lines.append(f"| {b} vs true_iv | {m:.3e} | {int(np.isnan(iv[b]).sum())} NaN |")

    # Split the C++ vs Python comparison by which C++ path solved the row.
    newton = status == 0
    brent = status == 1
    d = np.abs(iv["cpp"] - iv["python"])
    lines += [
        "",
        "C++ solver path breakdown (from status codes):",
        "",
        "| Path | contracts | share | max abs diff vs python |",
        "|---|---|---|---|",
        f"| Newton converged | {newton.sum():,} | {newton.mean():.1%} | "
        f"{np.nanmax(d[newton]) if newton.any() else float('nan'):.3e} |",
        f"| Brent fallback | {brent.sum():,} | {brent.mean():.1%} | "
        f"{np.nanmax(d[brent]) if brent.any() else float('nan'):.3e} |",
        f"| failed (NaN) | {(status < 0).sum():,} | {(status < 0).mean():.1%} | n/a |",
        "",
    ]
    Path(args.out).write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))

    np.savez(Path(args.out).with_suffix(".npz"), **iv, status=status)


if __name__ == "__main__":
    main()
